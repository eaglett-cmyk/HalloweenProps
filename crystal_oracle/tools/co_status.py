"""
============================================================================
 co_status.py  -  assets/ASSET-STATUS.md writer (Crystal Oracle)
----------------------------------------------------------------------------
 One page that answers "what's done?": per still / clip / voice line / sfx /
 music bed - does the source exist, was it built, real or placeholder,
 priority - MVP first, with counts, a cue-coverage table (what the firmware
 will play for every cue) and every problem the manifest check found.
 Python 3 standard library only.
============================================================================
"""
import os

import co_manifest as cm

PLACEHOLDER_MODES = {"test": "PLACEHOLDER (test card)", "tts": "PLACEHOLDER (Windows TTS)", "synth": "PLACEHOLDER (synth)"}


def _cell(s, n=None):
    s = "" if s is None else str(s)
    s = s.replace("|", "/").replace("\n", " ")
    if n and len(s) > n:
        s = s[:n - 1] + "~"
    return s


def _pri_sorted(entries):
    return sorted(entries, key=lambda e: 0 if e.get("priority") == "MVP" else 1)


def output_state(path, cache_out, failed):
    """(state text, cache entry or None)."""
    ent = cache_out.get(os.path.normcase(os.path.abspath(path))) if path else None
    if failed:
        return ("FAILED this run" + (" (older output kept)" if path and os.path.exists(path) else "")), ent
    if not path or not os.path.exists(path):
        return "MISSING", None
    if not ent:
        return "PRESENT (not built by this tool)", None
    return PLACEHOLDER_MODES.get(ent.get("mode"), "REAL"), ent


def _kb(n):
    return "%.1f KB" % (n / 1024.0) if n < 1024 * 1024 else "%.2f MB" % (n / 1048576.0)


def write_status(path, model, ctx, report, run_info):
    """ctx: dict with out_root, rel(), clip_out(c) -> (path, alt), audio_out(cat, id), cache_outputs,
    failed (set of (cat, id)), manifest_rel, link_state, orphans."""
    co = ctx["cache_outputs"]
    failed = ctx["failed"]
    lines = []
    A = lines.append
    A("# Asset status - %s" % (model.title or "Crystal Oracle"))
    A("")
    A("Generated %s by `tools/build_assets.py` from `%s` (output: `%s`). Regenerated by every run - don't edit."
      % (run_info["when"], ctx["manifest_rel"], ctx["out_rel"]))
    A("")
    A("States: **REAL** = built from your source file; **PLACEHOLDER** = test card / synth sound / Windows TTS "
      "(`--test-clips`, `--placeholders`); **MISSING** = nothing on the card - the firmware falls back to a built-in "
      "animation / chime (or silence for voice).")
    A("")

    # ---------------- rows ----------------
    still_rows, clip_rows, voice_rows, sfx_rows, music_rows = [], [], [], [], []
    counts = {}

    def bump(cat, pri, has_src, state):
        c = counts.setdefault(cat, {"n": 0, "mvp": 0, "src": 0, "mvp_src": 0, "real": 0, "ph": 0, "missing": 0})
        c["n"] += 1
        c["mvp"] += pri == "MVP"
        c["src"] += bool(has_src)
        c["mvp_src"] += bool(has_src) and pri == "MVP"
        if state is not None:
            if state.startswith("REAL"):
                c["real"] += 1
            elif state.startswith("PLACEHOLDER"):
                c["ph"] += 1
            elif state.startswith("MISSING") or state.startswith("FAILED"):
                c["missing"] += 1

    for st in _pri_sorted(list(model.stills.values())):
        pr = st.get("probe")
        size = "%dx%d" % (pr[0], pr[1]) if pr else ""
        alpha = ("yes" if pr[2] else "no") if pr else ""
        src = os.path.basename(st["src"]) if st["src"] else "**missing**"
        bump("stills", st["priority"], st["src"], None)
        still_rows.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            st["id"], st["priority"], st["kind"], _cell(src), size,
            alpha + (" (keyed)" if st["transparent"] and pr and not pr[2] and st["key"] is not False else ""),
            _cell(", ".join(st["clips"] or st["used_by"]), 60), _cell(st["desc"], 70)))

    for c in _pri_sorted(model.clips):
        p, alt = ctx["clip_out"](c)
        if not os.path.exists(p) and alt and os.path.exists(alt):
            p = alt
        state, ent = output_state(p, co, ("clip", c["id"]) in failed)
        ins = cm.clip_sources(c, model)
        src_txt = ", ".join(("%s" % lab) if pth else ("**%s missing**" % lab) for lab, pth in ins)
        has = all(pth for _, pth in ins)
        info = ""
        if ent and ent.get("info"):
            i = ent["info"]
            if c["recipe"] == "still" and ent.get("mode") != "test":
                info = _kb(i.get("bytes", 0))
            else:
                info = "%d fr, %.1f s, max %s, %s total, q%s" % (i.get("frames", 0), i.get("frames", 0) / (i.get("fps") or c["fps"]),
                                                                 _kb(i.get("max", 0)), _kb(i.get("bytes", 0)), i.get("q", "?"))
        bump("clips", c["priority"], has, state)
        clip_rows.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            c["id"], c["priority"], c["recipe"], _cell(src_txt, 80),
            ctx["rel"](p) if os.path.exists(p) else "", state, info))

    for cat, entries, rows in (("voice", model.voice, voice_rows), ("sfx", model.sfx, sfx_rows), ("music", model.music, music_rows)):
        for e in _pri_sorted(entries):
            p = ctx["audio_out"](cat, e["id"])
            state, ent = output_state(p, co, (cat, e["id"]) in failed)
            secs = ("%.2f s" % ent["info"]["seconds"]) if ent and ent.get("info", {}).get("seconds") is not None else ""
            src = os.path.basename(e["src"]) if e["src"] else "**missing**"
            bump(cat, e["priority"], e["src"], state)
            if cat == "voice":
                rows.append("| %s | %s | %s | %s | %s | %s | %s |" % (
                    e["id"], e["priority"], _cell(e["speaker"], 16), _cell(src), state, secs, _cell(e["text"], 80)))
            else:
                syn = e["synth"] or "(default)"
                rows.append("| %s | %s | %s | %s | %s | %s | %s |" % (
                    e["id"], e["priority"], _cell(src), state, secs, syn, _cell(e["desc"], 60)))

    # ---------------- summary ----------------
    A("## Summary")
    A("")
    A("| | entries | MVP | sources | MVP sources | built REAL | PLACEHOLDER | MISSING |")
    A("|---|---|---|---|---|---|---|---|")
    for cat in ("stills", "clips", "voice", "sfx", "music"):
        c = counts.get(cat, {"n": 0, "mvp": 0, "src": 0, "mvp_src": 0, "real": 0, "ph": 0, "missing": 0})
        if cat == "stills":
            A("| stills | %d | %d | %d | %d | - | - | - |" % (c["n"], c["mvp"], c["src"], c["mvp_src"]))
        else:
            A("| %s | %d | %d | %d | %d | %d | %d | %d |" % (cat, c["n"], c["mvp"], c["src"], c["mvp_src"], c["real"], c["ph"], c["missing"]))
    A("")
    A("(For clips, *sources* = clips whose every input exists.) Manifest check: **%d errors, %d warnings**. "
      "crystal_link.h: %s." % (len(report.errors), len(report.warnings), ctx["link_state"]))
    A("")

    # ---------------- coverage ----------------
    A("## Cue coverage (what the firmware will play)")
    A("")
    A("| cue | visual | voice lines |")
    A("|---|---|---|")
    have_vis = {}
    for c in model.clips:
        p, alt = ctx["clip_out"](c)
        if os.path.exists(p) or (alt and os.path.exists(alt)):
            have_vis[c["id"]] = output_state(p if os.path.exists(p) else alt, co, False)[0]
    vgroups = {}
    for v in model.voice:
        if os.path.exists(ctx["audio_out"]("voice", v["id"])):
            vgroups.setdefault(v["group"], []).append(v["variant"])
    group_map = {"attract": ["attract_call"], "chapter": ["chapter_%s" % x for x in "abcdef"],
                 "awaken": ["awaken", "awaken_a", "awaken_b", "awaken_c"], "greet": ["greet_r%d" % i for i in range(2, 8)],
                 "recall": ["recall_t%d" % i for i in range(4)], "absorb": [],
                 "moonfull": ["moonfull_a", "moonfull_b"],
                 "reveal_t0": ["reveal_t0", "rush_t0"], "reveal_t1": ["reveal_t1", "rush_t1"],
                 "reveal_t2": ["reveal_t2", "rush_t2"], "reveal_t3": ["reveal_t3", "rush_t3"]}
    for cue in cm.COVERAGE_VISUALS + ["bowl", "rankup"]:
        vis = [k for k in have_vis if k == cue or k.startswith(cue + "_")]
        vtxt = ", ".join("%s (%s)" % (k, "placeholder" if have_vis[k].startswith("PLACEHOLDER") else "real") for k in sorted(vis)) \
            if vis else ("-" if cue in ("bowl", "rankup") else "procedural fallback")
        groups = group_map.get(cue, ["bowl_common", "bowl_rare", "bowl_legend"] if cue == "bowl"
                               else (["rankup_r%d" % i for i in range(2, 8)] if cue == "rankup" else [cue]))
        groups = groups + [t for g in groups for t in cm.subst_targets(model, g) if t not in groups]
        vs = ["%s x%d" % (g, len(vgroups[g])) for g in groups if g in vgroups]
        A("| %s | %s | %s |" % (cue, _cell(vtxt, 90), ", ".join(vs) if vs else ("-" if not groups else "none")))
    A("")

    # ---------------- tables ----------------
    A("## Stills (ChatGPT images -> `assets/source/images/<id>.png`)")
    A("")
    A("| id | pri | kind | source | size | alpha | used by | description |")
    A("|---|---|---|---|---|---|---|---|")
    lines.extend(still_rows or ["| (none) | | | | | | | |"])
    A("")
    A("## Clips (`/oracle/clips`)")
    A("")
    A("| id | pri | recipe | inputs | output | state | info |")
    A("|---|---|---|---|---|---|---|")
    lines.extend(clip_rows or ["| (none) | | | | | | |"])
    A("")
    A("## Voice (`assets/source/voice/<id>.wav|mp3|m4a...` -> `/oracle/voice`)")
    A("")
    A("| id | pri | speaker | source | state | length | text |")
    A("|---|---|---|---|---|---|---|")
    lines.extend(voice_rows or ["| (none) | | | | | | |"])
    A("")
    A("## Sound effects (`/oracle/sfx`)")
    A("")
    A("| id | pri | source | state | length | placeholder synth | description |")
    A("|---|---|---|---|---|---|---|")
    lines.extend(sfx_rows or ["| (none) | | | | | | |"])
    A("")
    A("## Music (`/oracle/music`)")
    A("")
    A("| id | pri | source | state | length | placeholder synth | description |")
    A("|---|---|---|---|---|---|---|")
    lines.extend(music_rows or ["| (none) | | | | | | |"])
    A("")
    if ctx.get("orphans"):
        A("## Files on the card that the manifest doesn't know")
        A("")
        A("The firmware still uses these. `--clean` removes them.")
        A("")
        for o in ctx["orphans"]:
            A("- `%s`" % o)
        A("")
    A("## Manifest check")
    A("")
    if not (report.errors or report.warnings or report.infos):
        A("No problems.")
    for title, items in (("Errors", report.errors), ("Warnings", report.warnings), ("Notes", report.infos)):
        if items:
            A("**%s**" % title)
            A("")
            for it in items:
                A("- " + it)
            A("")
    text = "\n".join(lines).rstrip() + "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return counts
